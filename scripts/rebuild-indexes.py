#!/usr/bin/env python3
"""Regenerate the root INDEX.md from each page's `description:` frontmatter.

Never edit INDEX.md by hand: edit the page's `description:` and re-run this
(the pre-commit hook does it for you and stages the result).

Usage: rebuild-indexes.py [--root DIR]   (DIR defaults to this repo; the
pre-commit hook passes an export of the staged tree, so the committed
INDEX.md lists only pages that are part of the commit)
"""
from __future__ import annotations
import json, re, sys
from pathlib import Path


def _root_from_argv() -> Path:
    """`--root DIR` points the script at another checkout of the KB, such as the
    staged tree the pre-commit hook exports; the default is this repo."""
    argv = sys.argv[1:]
    for i, a in enumerate(argv):
        if a == '--root' and i + 1 < len(argv):
            return Path(argv[i + 1]).resolve()
        if a.startswith('--root='):
            return Path(a.split('=', 1)[1]).resolve()
    return Path(__file__).resolve().parents[1]


ROOT = _root_from_argv()
SCHEMA = json.loads((Path(__file__).resolve().parent / 'kb-schema.json').read_text(encoding='utf-8'))
SKIP_DIRS = set(SCHEMA['index_skip_dirs'])
ROOT_SKIP = set(SCHEMA['freeform_files'])
FM_RE = re.compile(r'^---\s*\n(.*?)\n---\s*\n', re.S)


def parse_fm(text: str) -> dict[str, str]:
    m = FM_RE.match(text)
    if not m:
        return {}
    out = {}
    for line in m.group(1).splitlines():
        if ':' in line and not line.startswith((' ', '\t', '-')):
            k, v = line.split(':', 1)
            out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def should_index(path: Path) -> bool:
    rel = path.relative_to(ROOT)
    if any(part in SKIP_DIRS for part in rel.parts):
        return False
    if path.name in {'README.md', 'INDEX.md'}:
        return False
    if len(rel.parts) == 1 and rel.name in ROOT_SKIP:
        return False
    return path.suffix == '.md'


def main() -> None:
    entries = []
    for path in sorted(ROOT.rglob('*.md')):
        if not should_index(path):
            continue
        fm = parse_fm(path.read_text(encoding='utf-8'))
        desc = fm.get('description')
        if not desc:
            continue
        rel = path.relative_to(ROOT).as_posix()
        title = fm.get('title') or path.stem.replace('-', ' ').title()
        folder = rel.split('/')[0] if '/' in rel else 'root'
        entries.append((folder, rel, title, fm.get('type', 'note'), fm.get('status', ''), desc))

    lines = [
        '<!-- GENERATED by scripts/rebuild-indexes.py — edit description: frontmatter, not this file -->',
        '# Index',
        '',
    ]
    if not entries:
        lines.append('_No pages yet. Pages appear here once they have `description:` frontmatter._')
    current = None
    for folder, rel, title, typ, status, desc in entries:
        if folder != current:
            if current is not None:
                lines.append('')
            current = folder
            lines.append(f'## {folder}')
            lines.append('')
        status_part = f' · {status}' if status else ''
        lines.append(f'- [[{rel[:-3]}|{title}]] — {desc} (`{typ}`{status_part})')

    (ROOT / 'INDEX.md').write_text('\n'.join(lines).rstrip() + '\n', encoding='utf-8')
    print(f'wrote INDEX.md with {len(entries)} entries')


if __name__ == '__main__':
    main()
